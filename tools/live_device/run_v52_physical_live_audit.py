"""
KARVISH V52 — PHYSICAL DEVICE LIVE AUDIT RUNNER
Executes live autonomous tasks on Samsung Galaxy A26 (RZCY51MQP9K)
powered by the neural Karvish V52 model running on the RTX 4050 GPU.

Audits every single decision:
- Target candidate selection
- Action type
- Pointer argument extraction (zero regex)
- Inference latency
- Physical screen mutation & success verification
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(line_buffering=True, encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(line_buffering=True, encoding="utf-8")

REPO_ROOT = Path(".").resolve()
ADB_PATH = os.path.expandvars(r"%LOCALAPPDATA%\Android\Sdk\platform-tools\adb.exe")
DEVICE_SERIAL = "RZCY51MQP9K"
OUTPUT_DIR = REPO_ROOT / "tools" / "live_device" / "v52_live_audit_reports"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
AUDIT_LOG_FILE = REPO_ROOT / "tools" / "live_device" / "v52_live_physical_audit.jsonl"


def run_adb(args: List[str], timeout: int = 15) -> str:
    cmd = [ADB_PATH, "-s", DEVICE_SERIAL] + args
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=timeout)
        return res.stdout.strip()
    except Exception as e:
        return f"ADB_ERROR: {e}"


def check_gpu_server() -> bool:
    try:
        import urllib.request
        with urllib.request.urlopen("http://localhost:8765/health", timeout=3) as resp:
            data = json.loads(resp.read().decode())
            return data.get("status") == "ready" and data.get("model") == "KarvishModelV52"
    except Exception:
        return False


def run_v52_live_task(
    goal: str,
    pkg: Optional[str] = None,
    timeout: int = 40,
    success_keywords: Optional[List[str]] = None,
) -> Dict[str, Any]:
    print("\n" + "=" * 80)
    print(f"RUNNING V52 PHYSICAL LIVE TASK ON SAMSUNG GALAXY A26")
    print(f"Goal: '{goal}'")
    print(f"Target Package: {pkg}")
    print(f"Device: {DEVICE_SERIAL}")
    print("=" * 80, flush=True)

    assert check_gpu_server(), "V52 GPU Server is not running on port 8765!"

    # 1. Reverse Port Forwarding
    run_adb(["reverse", "tcp:8765", "tcp:8765"])

    # 2. Reset device state to clean home screen
    run_adb(["shell", "input keyevent 224"])  # Wake up screen
    run_adb(["shell", "input keyevent 82"])   # Unlock screen
    run_adb(["shell", "input keyevent 3"])    # Press HOME
    # Force-stop common test apps so tests do not cross-contaminate
    for p in ["com.linkedin.android", "com.google.android.youtube", "com.android.chrome", "com.sec.android.app.popupcalculator", "com.android.settings", "com.android.vending"]:
        run_adb(["shell", f"am force-stop {p}"])
        if "calc" in p:
            run_adb(["shell", f"pm clear {p}"])
    if pkg:
        run_adb(["shell", f"am force-stop {pkg}"])
    run_adb(["shell", "input keyevent 3"])
    time.sleep(1.0)

    # 3. Ensure Karvish Accessibility Service is active
    run_adb(["shell", "settings", "put", "secure", "enabled_accessibility_services", "com.zipper.app/.accessibility.KarvishAccessibilityService"])
    run_adb(["shell", "settings", "put", "secure", "accessibility_enabled", "1"])
    run_adb(["shell", "logcat", "-c"])

    # Reset server-side audit log
    if AUDIT_LOG_FILE.exists():
        open(AUDIT_LOG_FILE, "w").close()

    # 4. Dispatch Agent Intent
    t0 = time.time()
    intent_cmd = (
        f"am start -n com.zipper.app/.MainActivity "
        f"--es run_agent_goal \"{goal}\" "
        f"--ez enable_active_recovery false "
        f"--ez use_remote_ranker true"
    )
    launch_res = run_adb(["shell", intent_cmd])
    print(f">> Dispatched Karvish Agent intent to phone: {launch_res}", flush=True)

    # 5. Monitor Live Turns and Audit Stream
    completed = False
    stopped = False
    start_marker = f"Goal: '{goal}'"
    turns_observed: List[Dict[str, Any]] = []

    while time.time() - t0 < timeout:
        time.sleep(1.5)
        elapsed = round(time.time() - t0, 1)

        # Read audit entries generated by V52 GPU server
        if AUDIT_LOG_FILE.exists():
            with open(AUDIT_LOG_FILE, "r", encoding="utf-8") as f:
                current_turns = [json.loads(line) for line in f if line.strip()]
                if len(current_turns) > len(turns_observed):
                    new_turns = current_turns[len(turns_observed):]
                    for t in new_turns:
                        dispatched = t.get('dispatched_action', t.get('neural_action'))
                        text_info = f" | Arg: '{t['extracted_span']}'" if t.get('extracted_span') else ""
                        print(
                            f"  [TURN {t['turn']} | T+{elapsed}s] "
                            f"Neural: {t['neural_action']} -> Dispatched: {dispatched} | "
                            f"Target: '{t['selected_candidate']['label']}'"
                            f"{text_info} | Conf: {t['confidence']:.2f} | Latency: {t['latency_ms']}ms",
                            flush=True,
                        )
                    turns_observed = current_turns

        # Check logcat for completion or termination
        raw_logs = run_adb(["shell", "logcat", "-d", "-s", "KarvishAgentService", "KarvishAgentRuntime", "LiveRankerModelEngine", "KarvishActionDispatcher"])
        if "AUTONOMOUS GOAL ACHIEVED" in raw_logs or "GOAL COMPLETED" in raw_logs or "TERMINATING (GOAL_SUCCESS)" in raw_logs:
            completed = True
            print(f">> [RESULT] Goal achieved on phone in {elapsed}s!", flush=True)
            break
        if "AGENT STOPPED" in raw_logs or "TERMINATING" in raw_logs or "Goal declared unreachable" in raw_logs or "STUCK_NO_PROGRESS" in raw_logs:
            stopped = True
            print(f">> [RESULT] Agent terminated in {elapsed}s (Stopped / Stuck).", flush=True)
            break

    duration = round(time.time() - t0, 2)

    # 6. Capture Final Screen Verification
    screen_cap_path = OUTPUT_DIR / f"v52_audit_{int(time.time())}.png"
    try:
        img_bytes = subprocess.check_output([ADB_PATH, "-s", DEVICE_SERIAL, "exec-out", "screencap", "-p"], timeout=10)
        with open(screen_cap_path, "wb") as f:
            f.write(img_bytes)
        print(f">> Final screen captured to: {screen_cap_path.name}")
    except Exception as e:
        print(f">> Screen capture warning: {e}")

    # 7. Pull Current UI Hierarchy dump
    ui_dump = run_adb(["shell", "uiautomator", "dump", "/data/local/tmp/v52_dump.xml"])
    ui_xml = run_adb(["shell", "cat", "/data/local/tmp/v52_dump.xml"])

    # 8. Success Verification: ONLY if completed or specific goal target was reached
    keyword_matches = []
    if success_keywords:
        for kw in success_keywords:
            if kw.lower() in ui_xml.lower():
                keyword_matches.append(kw)

    # Honest verification: must actually complete or prove task fulfillment
    success_verified = completed and (len(keyword_matches) > 0 if success_keywords else True)

    task_report = {
        "goal": goal,
        "package": pkg,
        "device": DEVICE_SERIAL,
        "duration_sec": duration,
        "completed": completed,
        "success_verified": success_verified,
        "keyword_matches": keyword_matches,
        "turns_executed": len(turns_observed),
        "audit_trace": turns_observed,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
    }

    report_file = OUTPUT_DIR / f"v52_audit_task_report_{int(time.time())}.json"
    with open(report_file, "w", encoding="utf-8") as f:
        json.dump(task_report, f, indent=2)

    print("=" * 80)
    print(f"V52 PHYSICAL AUDIT SUMMARY:")
    print(f"Goal: {goal}")
    print(f"Duration: {duration}s | Turns: {len(turns_observed)} | Completed: {completed}")
    print(f"Verified via Live UI Evidence: {'YES' if success_verified else 'NO'}")
    print(f"Keywords Found: {keyword_matches}")
    print(f"Detailed Report: {report_file.name}")
    print("=" * 80 + "\n", flush=True)

    return task_report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="V52 Physical Live Audit Runner")
    parser.add_argument("--goal", type=str, default="Open Settings and search for Battery", help="Task goal")
    parser.add_argument("--pkg", type=str, default="com.android.settings", help="App package")
    parser.add_argument("--timeout", type=int, default=35, help="Timeout in seconds")
    parser.add_argument("--keywords", nargs="+", default=["Battery", "Settings"], help="Success keywords")
    args = parser.parse_args()

    run_v52_live_task(
        goal=args.goal,
        pkg=args.pkg,
        timeout=args.timeout,
        success_keywords=args.keywords,
    )
